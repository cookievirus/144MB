FIRST, LAST = 32, 126
CELL_W, CELL_H = 6, 8
GLYPH_W, GLYPH_H = 5, 7


def rows_for(ch):
    g = GLYPHS.get(ch)
    if g is None:
        raise KeyError("missing glyph for %r (0x%02X)" % (ch, ord(ch)))
    if len(g) != GLYPH_H or any(len(r) != GLYPH_W for r in g):
        raise ValueError("glyph %r is not %dx%d" % (ch, GLYPH_W, GLYPH_H))
    # Bit 7 is the leftmost column, so a row blits with a plain left shift.
    return [sum(0x80 >> i for i, c in enumerate(r) if c != " ") for r in g]


def table():
    """Flat list of (LAST-FIRST+1) * GLYPH_H bytes."""
    out = []
    for code in range(FIRST, LAST + 1):
        out.extend(rows_for(chr(code)))
    return out
